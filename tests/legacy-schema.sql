CREATE TABLE progress(id TEXT PRIMARY KEY,status INTEGER NOT NULL);
CREATE TABLE favorite(id TEXT PRIMARY KEY);
CREATE TABLE attempt(id INTEGER PRIMARY KEY AUTOINCREMENT,token TEXT UNIQUE,chapter INTEGER,correct INTEGER,total INTEGER,at INTEGER,kind TEXT);
CREATE TABLE answer(attempt INTEGER,question TEXT,user TEXT,correct INTEGER,PRIMARY KEY(attempt,question));
CREATE TABLE wrong(id TEXT PRIMARY KEY,count INTEGER,mastered INTEGER,at INTEGER);
